// @env node
import { readFile, writeFile } from 'node:fs/promises'
import process from 'node:process'
import { z } from 'zod'
import { baseCopy } from '../src/data/base-copy.ts'
import { componentCopy } from '../src/data/component-copy.ts'
import { cvSchema } from '../src/data/schema.ts'

const destination = new URL('../cv.schema.json', import.meta.url)
const schema = z.toJSONSchema(cvSchema, {
  io: 'input',
  target: 'draft-07',
  unrepresentable: 'any',
})
const copy = {
  ...baseCopy,
  ...componentCopy,
}
const ui = schema.properties?.ui
if (ui && typeof ui === 'object') {
  ui.properties = Object.fromEntries(Object.entries(copy).sort(([a], [b]) => a.localeCompare(b)).map(([key, value]) => [
    key,
    {
      type: 'string',
      description: `Interface copy: ${key}. Keep any {placeholder} tokens intact.`,
      examples: [value],
    },
  ]))
}
const output = {
  ...schema,
  $id: 'https://raw.githubusercontent.com/MiraHikari/astro-constructivist/main/cv.schema.json',
  title: 'Constructa site configuration',
  description: 'Content, presentation, navigation, SEO, and interface copy for Constructa. Run pnpm check-config for runtime validation.',
  $comment: 'Generated from src/data/schema.ts. Zod refinements and preprocessing remain authoritative; do not edit this file by hand.',
}
const formatted = `${JSON.stringify(output, null, 2)}\n`

if (process.argv.includes('--check')) {
  const current = await readFile(destination, 'utf8').catch(() => '')
  if (current !== formatted) {
    console.error('cv.schema.json is missing or stale. Run pnpm schema and commit the generated file.')
    process.exitCode = 1
  }
  else {
    console.log('cv.schema.json matches the runtime schema.')
  }
}
else {
  await writeFile(destination, formatted)
  console.log('Generated cv.schema.json from the runtime schema.')
}
