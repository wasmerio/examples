export function toTrad(input: string): string {
  // Whole-word terms first, then characters — otherwise 文档 becomes 文檔 and
  // the 文档→文件 rule can never match again.
  let out = input;
  for (const [re, to] of TERMS) out = out.replace(re, to);
  let chars = '';
  for (const ch of out) chars += CHARS[ch] ?? ch;
  return chars;
}

/** Pick a Chinese string and convert it for zh-Hant pages. */
export function pickTrad(lang: string, text: string): string {
  return lang === 'zh-hant' ? toTrad(text) : text;
}
